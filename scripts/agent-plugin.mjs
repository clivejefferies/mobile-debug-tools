import assert from 'node:assert/strict'
import { copyFileSync, cpSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const repositoryRoot = fileURLToPath(new URL('../', import.meta.url))
const pluginRoot = path.join(repositoryRoot, 'agent-plugin')
const packagedSkill = path.join(pluginRoot, 'skills/mobile-debug-mcp/SKILL.md')
const packagedLicense = path.join(pluginRoot, 'LICENSE')
const sourceLicense = path.join(repositoryRoot, 'LICENSE')
const packageInfo = JSON.parse(readFileSync(path.join(repositoryRoot, 'package.json'), 'utf8'))
const plugin = JSON.parse(readFileSync(path.join(pluginRoot, 'plugin.json'), 'utf8'))
const mcp = JSON.parse(readFileSync(path.join(pluginRoot, 'mcp.json'), 'utf8'))
const { $schema: _pluginSchema, extensions, ...pluginMetadata } = plugin
const { $schema: _mcpSchema, ...codexMcp } = mcp
const codexManifest = {
  ...pluginMetadata,
  skills: './skills/',
  mcpServers: './.mcp.json',
  interface: extensions['com.openai'].interface,
}
const sharedMetadata = Object.fromEntries(
  ['name', 'version', 'description', 'author', 'repository', 'license'].map(key => [key, plugin[key]]),
)
const claudeManifest = {
  ...sharedMetadata,
  mcpServers: {
    [packageInfo.name]: {
      command: 'npx',
      args: ['--yes', `${packageInfo.name}@${packageInfo.version}`, 'server'],
    },
  },
}
const cursorManifest = {
  ...sharedMetadata,
  skills: './skills/',
  mcpServers: {
    [packageInfo.name]: {
      type: 'stdio',
      command: 'npx',
      args: ['--yes', `${packageInfo.name}@${packageInfo.version}`, 'server'],
      cwd: '${CURSOR_PLUGIN_ROOT}',
    },
  },
}
const antigravityManifest = {
  $schema: 'https://antigravity.google/schemas/v1/plugin.json',
  ...sharedMetadata,
  displayName: extensions['com.openai'].interface.displayName,
  logo: 'assets/mobile-debug-tools.svg',
  suggestedPrompts: extensions['com.openai'].interface.defaultPrompt,
}
const antigravityMcp = {
  mcpServers: Object.fromEntries(Object.entries(codexMcp.mcpServers).map(([name, server]) => {
    const { type: _transport, ...settings } = server
    return [name, settings]
  })),
}
const mcpConfigs = [
  ['.mcp.json', codexMcp],
  ['mcp_config.json', antigravityMcp],
]
const manifests = [
  ['.codex-plugin/plugin.json', codexManifest],
  ['.claude-plugin/plugin.json', claudeManifest],
  ['.cursor-plugin/plugin.json', cursorManifest],
  ['.antigravity-plugin/plugin.json', antigravityManifest],
]

const cursorFiles = [
  ['.cursor-plugin/plugin.json', `${JSON.stringify(cursorManifest, null, 2)}\n`],
  ['skills/mobile-debug-mcp/SKILL.md', readFileSync(packagedSkill)],
  ['LICENSE', readFileSync(sourceLicense)],
  ['README.md', '# Mobile Debug Tools for Cursor\n\nGenerated by `npm run sync:agent-plugin`; edit the canonical plugin source.\n\nCopy the contents of this directory into `~/.cursor/plugins/local/mobile-debug-tools`,\nthen run Developer: Reload Window and check Customize for the skill and MCP server.\nDo not copy the portable parent plugin: its `${PLUGIN_DATA}` variable is not expanded by Cursor.\n\nSetup and support: https://github.com/clivejefferies/mobile-debug-tools\n'],
]
if (process.argv[2] === '--sync') {
  copyFileSync(sourceLicense, packagedLicense)
  for (const [relativePath, contents] of cursorFiles) {
    const target = path.join(pluginRoot, 'cursor', relativePath)
    mkdirSync(path.dirname(target), { recursive: true })
    writeFileSync(target, contents)
  }
  for (const [relativePath, config] of mcpConfigs) {
    writeFileSync(path.join(pluginRoot, relativePath), `${JSON.stringify(config, null, 2)}\n`)
  }
  for (const [relativePath, manifest] of manifests) {
    const manifestPath = path.join(pluginRoot, relativePath)
    mkdirSync(path.dirname(manifestPath), { recursive: true })
    writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`)
  }
}
else if (!['--check', '--export-antigravity'].includes(process.argv[2])) throw new Error('Use --sync, --check or --export-antigravity <new-directory>')

assert.equal(plugin.$schema, 'https://agent-plugins.org/schemas/1.0.0/plugin.schema.json')
assert.equal(plugin.name, 'mobile-debug-tools')
assert.match(plugin.version, /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/, 'plugin releases use an independent semantic version')
assert.equal(mcp.$schema, 'https://agent-plugins.org/schemas/1.0.0/mcp.schema.json')
const servers = Object.entries(mcp.mcpServers)
assert.equal(servers.length, 1, 'the plugin should expose only this MCP server')
const [serverName, server] = servers[0]
assert.equal(serverName, packageInfo.name)
assert.equal(server.type, 'stdio')
assert.equal(server.command, 'npx')
assert.deepEqual(server.args, ['--yes', `${packageInfo.name}@${packageInfo.version}`, 'server'])
assert.equal(server.cwd, '${PLUGIN_DATA}', 'npx must run outside the same-named source checkout')
assert.deepEqual(readFileSync(packagedLicense), readFileSync(sourceLicense), 'packaged license must match its source')
for (const [relativePath, config] of mcpConfigs) {
  assert.deepEqual(JSON.parse(readFileSync(path.join(pluginRoot, relativePath), 'utf8')), config, `${relativePath} must match the portable MCP configuration`)
}
assert.ok(readFileSync(path.join(pluginRoot, antigravityManifest.logo)).length > 0, 'Antigravity logo must be bundled')
for (const [relativePath, expectedManifest] of manifests) {
  assert.deepEqual(
    JSON.parse(readFileSync(path.join(pluginRoot, relativePath), 'utf8')),
    expectedManifest,
    `${relativePath} must match the portable plugin`,
  )
}
for (const [relativePath, contents] of cursorFiles) {
  assert.deepEqual(readFileSync(path.join(pluginRoot, 'cursor', relativePath)), Buffer.from(contents), `Cursor native ${relativePath} must match its source`)
}
for (const marketplacePath of [
  '.agents/plugins/marketplace.json',
  '.claude-plugin/marketplace.json',
  '.cursor-plugin/marketplace.json',
]) {
  const marketplace = JSON.parse(readFileSync(path.join(repositoryRoot, marketplacePath), 'utf8'))
  assert.equal(marketplace.name, plugin.name, `${marketplacePath} name must match the plugin`)
  assert.equal(marketplace.plugins.length, 1, `${marketplacePath} must expose one plugin`)
  assert.equal(marketplace.plugins[0].name, plugin.name, `${marketplacePath} plugin name must match`)
  assert.equal(marketplace.plugins[0].source?.path ?? marketplace.plugins[0].source, marketplacePath.startsWith('.cursor-plugin') ? './agent-plugin/cursor' : './agent-plugin', `${marketplacePath} source must point to the plugin`)
}
const skillName = readFileSync(packagedSkill, 'utf8').match(/^---\r?\nname: ([a-z0-9-]+)\r?\n/)?.[1]
assert.equal(skillName, path.basename(path.dirname(packagedSkill)), 'packaged skill directory must match its frontmatter name')

console.log('Agent plugin package is in sync')

if (process.argv[2] === '--export-antigravity') {
  assert.ok(process.argv[3], 'Supply a new output directory for the Antigravity export')
  const target = path.resolve(process.argv[3])
  // Refuse existing directories rather than overwrite source or stale package files.
  mkdirSync(target)
  writeFileSync(path.join(target, 'plugin.json'), `${JSON.stringify(antigravityManifest, null, 2)}\n`)
  writeFileSync(path.join(target, 'mcp_config.json'), `${JSON.stringify(antigravityMcp, null, 2)}\n`)
  copyFileSync(path.join(pluginRoot, '.antigravity-plugin/README.md'), path.join(target, 'README.md'))
  copyFileSync(packagedLicense, path.join(target, 'LICENSE'))
  for (const directory of ['skills', 'assets']) cpSync(path.join(pluginRoot, directory), path.join(target, directory), { recursive: true, filter: file => path.basename(file) !== '.DS_Store' && !path.basename(file).startsWith('._') })
  console.log(`Antigravity package exported to ${target}`)
}
