import assert from 'node:assert/strict'
import { measure, compare } from '../../../scripts/code-quality.mjs'

const file = 'src/interact/quality-fixture.ts'
const inspect = (code: string) => measure(file, code)
const has = (findings: Awaited<ReturnType<typeof inspect>>, rule: string) => findings.some(f => f.rule === rule)
const baseline = (findings: Awaited<ReturnType<typeof inspect>>) => findings.map(({ line: _line, ...entry }) => ({ ...entry, reason: 'Test legacy exception' }))

async function main() {
  assert.deepEqual(await inspect('export const twice = (value: number) => value * 2'), [])
  const hugeClass = await inspect(`export class Huge {\n${Array.from({ length: 301 }, (_, i) => `field${i} = ${i}`).join('\n')}\n}`)
  assert(has(hugeClass, 'class-lines'))
  const hugeFunction = await inspect(`export function work() {\n${Array.from({ length: 81 }, (_, i) => `console.log(${i})`).join('\n')}\n}`)
  assert(has(hugeFunction, 'max-lines-per-function'))
  assert(has(await inspect(`export const work = () => {\n${'console.log(1)\n'.repeat(81)}}`), 'max-lines-per-function'))
  const hugeFile = await inspect(Array.from({ length: 501 }, (_, i) => `export const value${i} = ${i}`).join('\n'))
  assert(has(hugeFile, 'max-lines'))
  assert(!has(await inspect(`// A comment\n${'\n// comment\n'.repeat(600)}export const x = 1`), 'max-lines'))
  const complex = await inspect(`export function decide(value: number) { ${'if(value) console.log(value);'.repeat(21)} }`)
  assert(has(complex, 'complexity'))
  assert(has(await inspect('export function nested(x: boolean) { if(x){if(x){if(x){if(x){if(x){console.log(x)}}}}} }'), 'max-depth'))
  assert(has(await inspect("import { value } from '../server/tool-handlers.js'"), 'import-boundary'))
  assert(has(await inspect("export { value } from '../server/common.js'"), 'import-boundary'))
  assert(has(await inspect("type Args = import('../server/common.js').ToolCallArgs"), 'import-boundary'))
  assert(has(await inspect("const transport = require('../server/common.js')"), 'import-boundary'))
  assert(has(await inspect('/* eslint complexity: \"off\" */\nexport const value = 1'), 'inline-suppression'))
  assert(!has(await inspect("import type { Value } from '../contracts/value.js'"), 'import-boundary'))
  assert(has(await inspect('// eslint-disable\nexport const x = 1'), 'inline-suppression'))
  assert(has(await inspect('// eslint-disable-next-line complexity\nexport function f() {}'), 'inline-suppression'))
  const any = await inspect('export function legacy(value: any) { return value }')
  assert(has(any, 'explicit-any'))
  assert.deepEqual(compare(any, baseline(any)), [])
  assert(compare(any, []).some(e => e.includes('explicit-any')))
  const grown = await inspect('export function legacy(value: any): any { return value }')
  assert(compare(grown, baseline(any)).some(e => e.includes('explicit-any')))
  const renamed = await inspect('export function replacement(value: any) { return value }')
  assert(compare(renamed, baseline(any)).length >= 2, 'renames do not inherit debt')
  const moved = any.map(f => ({ ...f, file: 'src/interact/moved.ts' }))
  assert(compare(moved, baseline(any)).length >= 2, 'moves do not inherit debt')
  assert(compare([], baseline(any)).some(e => e.includes('obsolete')))
  assert(compare(any, baseline(grown)).some(e => e.includes('Lower baseline')))
  assert(compare(any, [...baseline(any), ...baseline(any)]).some(e => e.includes('Duplicate')))
  assert(compare(any, [{ ...baseline(any)[0], reason: '' }]).some(e => e.includes('Invalid')))
  const collision = await inspect('function same(x: number) {return x} function same(x: number) {return x}')
  assert(has(collision, 'duplicate-symbol'))
  assert(compare(collision, baseline(collision)).some(e => e.includes('duplicate-symbol')), 'identity collisions cannot be baseline exceptions')
  const suppressed = await inspect('// eslint-disable max-lines-per-function\n'+`function huge(){\n${'console.log(1)\n'.repeat(81)}}`)
  assert(has(suppressed, 'max-lines-per-function'), 'inline directives cannot hide metrics')
  const typeDebt = await inspect('type First = any; type Second = number')
  const shiftedTypeDebt = await inspect('type First = number; type Second = any')
  assert(compare(shiftedTypeDebt, baseline(typeDebt)).length >= 2, 'unrelated type declarations cannot offset each other')
  const java = await measure('src/debugger/java/Fixture.java', 'int field;\n'.repeat(501))
  assert(has(java, 'max-lines'))
  assert.deepEqual(await measure('src/debugger/java/Fixture.java', '// comment\n'.repeat(501)), [])
  assert(!has(await inspect('class Accessor { get value() { return 1 } set value(value: number) { console.log(value) } }'), 'duplicate-symbol'))
  console.log('PASS structural metrics, debt ratchet, boundaries and suppression protection')
}
main().catch(error => { console.error(error); process.exitCode = 1 })
